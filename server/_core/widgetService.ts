/**
 * B23 — the board service.
 *
 * No tRPC, no drizzle, no React. Takes a store and a reader as arguments, so
 * every rule below is testable without a database and the router over it stays
 * thin enough to be read in one screen.
 *
 * The shape is deliberate. `widgetsRouter.ts` cannot be verified in a container
 * without the branch, so nothing that matters lives in it: it resolves the
 * acting scope, calls one function here, returns. Everything worth a test is
 * here or further down in the pure core.
 */

