/**
 * The gate an action must pass, rerun at submission.
 *
 * Returns the blockers standing in the way right now — empty means clear.
 * Deliberately not given the tile, the payload or the board: a gate that could
 * see what the widget claimed might be tempted to agree with it.
 */
export type ActionGate = (args: {
  actor: RoleActor; action: string; subjectRef: string | null;
}) => Promise<readonly NamedBlocker[]>;

export type ActionOutcome =
  | { ok: true; action: string }
  | { ok: false; code: "NOT_PERMITTED" | "BLOCKED"; blockers: readonly NamedBlocker[] };

/**
 * Submit an action from a tile.
 *
 * A widget's button is not an authorization decision. The tile that offered it
 * was rendered from an answer that was true when it was read — five seconds
 * ago, or four hours ago out of a cache — and the conditions behind a dispatch,
 * a mechanic release or an invoice can change in between. So the gate runs
 * again here, from the actor and the subject, and the tile's own state is never
 * consulted.
 *
 * This is why `presentTile`'s `actionable` is a presentation flag and not a
 * permission: it decides whether a button is drawn, never whether the thing
 * behind it may happen.
 */
export async function submitBoardAction(
  deps: { gate: ActionGate },
  actor: RoleActor,
  req: { action: string; subjectRef: string | null; requiredPermission: string },
): Promise<ActionOutcome> {
  // Role first, from the actor's own permission set rather than the board's.
  if (!actor.permissions.includes(req.requiredPermission)) {
    return { ok: false, code: "NOT_PERMITTED", blockers: [] };
  }

  const blockers = await deps.gate({ actor, action: req.action, subjectRef: req.subjectRef });
  if (blockers.length > 0) return { ok: false, code: "BLOCKED", blockers };

  return { ok: true, action: req.action };
}

