/* Ports                                                               */
/* ------------------------------------------------------------------ */

export type StoredLayout = {
  /** External reference. Null on a create, where the store assigns one. */
  layoutRef: string;
  userId: number;
  roleKey: string;
  deviceClass: DeviceClass;
  name: string;
  isDefault: boolean;
  /** Bumped by the store on every authoritative write. Absent on a create. */
  revision?: number;
};

/**
 * What the service needs from persistence, and nothing more.
 *
 * `saveLayout` is one call rather than a write plus an unset, because "only one
 * default" has to happen inside a single transaction and an interface that
 * exposed two calls would let a caller do half of it.
 */
export type WidgetLayoutStore = {
  findLayout(q: {
    userId: number; roleKey: string; deviceClass: DeviceClass; layoutRef?: string;
  }): Promise<{ layout: StoredLayout; items: readonly LayoutItem[] } | null>;

  /**
   * Insert a new layout. The reference is generated by the store, never taken
   * from the client — a client that chooses its own reference is a client that
   * can choose somebody else's.
   */
  createLayout(
    layout: Omit<StoredLayout, "layoutRef"> & { layoutRef: null },
    items: readonly NormalizedItem[],
    unsetOtherDefaults: boolean,
  ): Promise<{ layoutRef: string }>;

  /**
   * Update an existing layout, but only if it belongs to this user, role,
   * device and tenant. Resolves ownership inside the transaction, before a
   * single item row is touched, and fails closed.
   */
  updateOwnedLayout(
    layout: StoredLayout,
    items: readonly NormalizedItem[],
    unsetOtherDefaults: boolean,
    tenantId: string,
    /**
     * The revision the client edited. Omitted means "no opinion" — used by
     * callers with no offline story. Supplied means compare-and-swap.
     */
    expectedRevision?: number,
  ): Promise<
    | { ok: true; revision?: number }
    | { ok: false; code?: "LAYOUT_CONFLICT"; serverRevision?: number }
  >;
};

/** One read per tile. The router binds this to the real procedures. */
export type TileReader = (task: ResolveTask) => Promise<WidgetPayload<unknown>>;

/**
 * Audit hook, called once per board read.
 *
 * A board is thirty reads a minute. Auditing each tile would bury the log that
 * exists to answer "who saw our compliance records", and each tile's own
 * procedure already audits itself. What is worth recording once is that a
 * person opened a board and how much of it they were shown — including how many
 * tiles were withheld, which is the number an audit would actually ask about.
 */
export type BoardAudit = (event: {
  userId: number; roleKey: string; layoutRef: string | null;
  tiles: number; withheld: number; unknown: number; failed: number;
}) => Promise<void>;

