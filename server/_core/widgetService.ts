export type Offer = {
  widgetKey: WidgetKey;
  title: string;
  variants: readonly string[];
  defaultVariant: string;
  category: string;
  /** True when this role is the widget's suggested audience. Ordering only. */
  recommended: boolean;
};

export function listOfferable(actor: RoleActor): readonly Offer[] {
  // Offers for the acting role only. A dispatcher-only widget must not appear
  // in a driver board's picker just because the account also dispatches.
  return offerableWidgets({ permissions: actor.permissions }, actor.roles).map((key) => {
    const def = definitionFor(key);
    return {
      widgetKey: key, title: def.title, variants: def.variants,
      defaultVariant: def.defaultVariant, category: def.category,
      recommended: def.suggestedFor.includes(actor.roleKey),
    };
  });
}

