export type BoardTile = {
  instanceRef: string;
  widgetKey: string;
  title: string;
  variant: string;
  payload: WidgetPayload<unknown>;
  /** Computed server-side so a second client cannot invent its own rules. */
  appearance: ReturnType<typeof presentTile>;
};

export type Board = {
  layoutRef: string | null;
  /** True when nothing was saved and this is the registry-derived starting board. */
  seeded: boolean;
  name: string;
  deviceClass: DeviceClass;
  tiles: readonly BoardTile[];
};

const titleOf = (widgetKey: string): string =>
  (widgetKey in ({} as Record<string, never>) ? widgetKey : safeTitle(widgetKey));

function safeTitle(widgetKey: string): string {
  try {
    return definitionFor(widgetKey as WidgetKey).title;
  } catch {
    // An unregistered key still needs a heading, or the tile that reports the
    // loss would have nothing to report it about.
    return widgetKey;
  }
}

/**
 * Open a board.
 *
 * A caller with nothing saved gets the registry-derived starting board rather
 * than an empty screen, and is told it was seeded so the UI can offer to keep
 * it. Nothing is written on a read.
 */
export async function openBoard(
  deps: { store: WidgetLayoutStore; read: TileReader; audit?: BoardAudit },
  actor: RoleActor,
  q: {
    deviceClass: DeviceClass; layoutRef?: string;
    connected?: boolean;
    subjects?: Readonly<Partial<Record<"self" | "unit" | "trailer" | "job" | "trip" | "org" | "branch", string>>>;
  },
): Promise<Board> {
  // Everything that decides what may be seen comes off the actor. The request
  // contributes only what the server cannot know: whether the device has a
  // signal and which unit it is sitting in.
  const ctx = contextFor(actor, { connected: q.connected ?? true, subjects: q.subjects ?? {} });

  const found = await deps.store.findLayout({
    userId: actor.userId, roleKey: actor.roleKey, deviceClass: q.deviceClass,
    ...(q.layoutRef === undefined ? {} : { layoutRef: q.layoutRef }),
  });

  const seeded = found === null;
  const items: readonly LayoutItem[] = found
    ? found.items
    : defaultBoardFor(ctx, q.deviceClass).map((b) => ({
        instanceRef: `seed:${b.widgetKey}`,
        widgetKey: b.widgetKey,
        variant: b.variant,
        position: b.position,
      }));

  const plan = planBoard(items, ctx);
  const results: readonly TileResult[] = await runBoard(plan, deps.read);

  const byRef = new Map(items.map((i) => [i.instanceRef, i]));
  const tiles: BoardTile[] = results.map((r) => {
    const title = safeTitle(r.widgetKey);
    return {
      instanceRef: r.instanceRef,
      widgetKey: r.widgetKey,
      title,
      variant: byRef.get(r.instanceRef)?.variant ?? "status",
      payload: r.payload,
      appearance: presentTile(r.payload, title),
    };
  });

  if (deps.audit) {
    await deps.audit({
      userId: actor.userId, roleKey: actor.roleKey,
      layoutRef: found?.layout.layoutRef ?? null,
      tiles: tiles.length,
      withheld: tiles.filter((t) => t.payload.state === "not_permitted").length,
      unknown: tiles.filter((t) => t.payload.state === "unknown").length,
      failed: tiles.filter((t) => t.payload.state === "failed").length,
    });
  }

  return {
    layoutRef: found?.layout.layoutRef ?? null,
    seeded,
    name: found?.layout.name ?? "Default board",
    deviceClass: q.deviceClass,
    tiles,
  };
}

