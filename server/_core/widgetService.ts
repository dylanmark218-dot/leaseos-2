/* Saving a board                                                       */
/* ------------------------------------------------------------------ */

export type SaveOutcome =
  | { ok: true; layoutRef: string; tiles: number; created: boolean; revision?: number }
  | { ok: false; rejections: readonly NamedRejection[] }
  /**
   * The board moved while this client was editing it.
   *
   * Named separately from a rejection because it is not the caller's mistake
   * and the remedy is different: a rejection is fixed by changing the board, a
   * conflict is resolved by choosing between two boards. Silently overwriting
   * would lose whoever saved second, which offline makes routine.
   */
  | { ok: false; code: "LAYOUT_CONFLICT"; serverRevision?: number };

/**
 * Rejections from a save outcome, or none.
 *
 * A conflict is not a rejection — nothing about the submitted board was wrong —
 * so the union separates them, and this keeps every caller from writing the
 * same `"rejections" in outcome` check slightly differently.
 */
export const rejectionsOf = (o: SaveOutcome): readonly NamedRejection[] =>
  o.ok || !("rejections" in o) ? [] : o.rejections;

/**
 * Save a board.
 *
 * The validation is `prepareLayoutSave`; this only performs what it approves.
 * If it refuses, nothing is written and every rejection is returned — a partial
 * save would leave a board the user did not arrange.
 */
export async function saveBoard(
  deps: { store: WidgetLayoutStore },
  actor: RoleActor,
  req: Omit<LayoutSaveRequest, "userId" | "roleKey" | "layoutRef"> & {
    layoutRef?: string | null;
    /** The revision this client edited, when it knows one. */
    expectedRevision?: number;
  },
): Promise<SaveOutcome> {
  const prepared = prepareLayoutSave(
    // Identity is the actor's, not the request's. The validator checks this
    // too; passing it from the request at all would be the hole.
    { ...req, userId: actor.userId, roleKey: actor.roleKey, layoutRef: req.layoutRef ?? null },
    { actingUserId: actor.userId, roles: actor.roles, permissions: actor.permissions },
  );
  if (!prepared.ok) return { ok: false, rejections: prepared.rejections };

  const unsetDefaults = prepared.sideEffects.some((e) => e.kind === "unset_other_defaults");

  // Create and update are separate store calls because they are separate
  // authorization problems. A create cannot collide with anyone; an update has
  // to prove ownership of an existing row before a single item is deleted.
  if (prepared.layout.layoutRef === null) {
    const created = await deps.store.createLayout(
      { ...prepared.layout, layoutRef: null }, prepared.items, unsetDefaults,
    );
    return { ok: true, layoutRef: created.layoutRef, tiles: prepared.items.length, created: true };
  }

  const outcome = await deps.store.updateOwnedLayout(
    { ...prepared.layout, layoutRef: prepared.layout.layoutRef },
    prepared.items,
    unsetDefaults,
    actor.tenantId,
    // Forwarded, not dropped. An earlier edit to this call was written and
    // never applied, so compare-and-swap lived in the store and could not be
    // reached through the service — the store's own tests passed because they
    // call it directly. A restore or an offline replay would have overwritten
    // a board that had moved, silently.
    req.expectedRevision,
  );
  if (!outcome.ok && outcome.code === "LAYOUT_CONFLICT") {
    return {
      ok: false, code: "LAYOUT_CONFLICT",
      ...(outcome.serverRevision !== undefined ? { serverRevision: outcome.serverRevision } : {}),
    };
  }
  if (!outcome.ok) {
    return {
      ok: false,
      rejections: [{
        code: "LAYOUT_NOT_OWNED_OR_NOT_FOUND",
        // One message for "does not exist" and for "is not yours". Two
        // messages would turn the save endpoint into a probe for whether a
        // given layoutRef belongs to somebody.
        detail: "no layout with that reference exists for this user, role and device",
      }],
    };
  }
  return {
    ok: true, layoutRef: prepared.layout.layoutRef, tiles: prepared.items.length, created: false,
    ...(outcome.revision !== undefined ? { revision: outcome.revision } : {}),
  };
}

