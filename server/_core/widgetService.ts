export type RestorePreview = {
  items: readonly { widgetKey: WidgetKey; variant: string; position: number; title: string }[];
  /** What the board currently holds, so the user can see what is being replaced. */
  replacing: number;
};

/**
 * What Restore Default would produce, without producing it.
 *
 * Derived from the registry and the actor — there is no second default list in
 * the UI to drift from this one. Only currently offerable widgets appear, so a
 * revoked permission cannot come back through the restore path: the board a
 * driver gets today is the board their permissions today allow.
 */
export function previewDefaultBoard(
  actor: RoleActor,
  deviceClass: DeviceClass,
  currentTileCount: number,
): RestorePreview {
  const items = defaultBoardFor(
    { roles: actor.roles, permissions: actor.permissions },
    deviceClass,
  ).map((b) => ({ ...b, title: definitionFor(b.widgetKey).title }));
  return { items, replacing: currentTileCount };
}

/**
 * Replace the board with the registry default.
 *
 * Goes through `saveBoard`, so it meets the same validation, the same ownership
 * check and the same compare-and-swap as any other save. A restore that wrote
 * directly to the store would be a second write path, and the second one is
 * always the one missing a check.
 */
export async function restoreDefaultBoard(
  deps: { store: WidgetLayoutStore },
  actor: RoleActor,
  req: {
    layoutRef?: string | null;
    expectedRevision?: number;
    deviceClass: DeviceClass;
    name: string;
    isDefault: boolean;
  },
): Promise<SaveOutcome> {
  const preview = previewDefaultBoard(actor, req.deviceClass, 0);
  return saveBoard({ store: deps.store }, actor, {
    layoutRef: req.layoutRef ?? null,
    ...(req.expectedRevision !== undefined ? { expectedRevision: req.expectedRevision } : {}),
    deviceClass: req.deviceClass,
    name: req.name,
    isDefault: req.isDefault,
    items: preview.items.map((b, i) => ({
      // Deterministic instance refs: restoring twice produces the same board,
      // which matters when the result is compared against a staged offline one.
      instanceRef: `default-${b.widgetKey}`,
      widgetKey: b.widgetKey,
      variant: b.variant,
      position: i,
    })),
  });
}
